#!/usr/bin/env python3
"""Builds src/Core/CatalogData.cs from the AddonForge catalog (MIT, see NOTICE).

Usage: python3 tools/build_catalog.py <path to AddonForge catalog/forever.json> <AddonForge commit>

The catalog is a list of pointers: where each addon's author publishes it. The updater downloads from
those publishers only, and installs only what has a published SHA-256 checksum.
What this script changes from the upstream file:
- Wago fields are dropped, and an entry that is only on Wago is left out.
- RestedXP takes the id the updater already uses ("rxp"), so saved choices keep working.
- A few descriptions, notices and links are rewritten so they describe the addon, not another app.
- Bundles, featured spots and download statistics are not used.
Moving the pinned commit forward is done through an issue, with the diff of the catalog reviewed.
"""
import json
import re
import sys

ID_MAP = {"restedxp": "rxp"}
DROP = {"buggrabber"}
DESC = {
	"svshim": "Forever beta workaround for saved variables not loading. Its download includes a script file, so the updater only links to it.",
	"leatrix-plus": "Popular quality-of-life bundle.",
	"leatrix-maps": "Map improvements.",
	"baganator": "Bag addon (needs Syndicator).",
	"auctionator": "Auction house helper.",
	"platynator": "Nameplate addon.",
	"bagnon": "Bag addon.",
	"whats-training": "Shows trainable spells.",
	"questie": "Quest helper. Its Forever version is not released yet.",
	"details": "Damage meter.",
	"elvui": "Full UI replacement. TukUI has no Forever build of it yet; the updater shows when one is listed.",
}
# Pages that replace the upstream link: Details! keeps the CurseForge page the updater has always opened for it.
URL = {"details": "https://www.curseforge.com/wow/addons/details"}
NOTICE = {
	"gatherlite": "The newest GitHub release is not a Forever build.",
	"svshim": "Beta workaround: remove it once saved variables load normally again.",
}
KEEP = ["id", "name", "desc", "category", "github", "asset_hint", "wowi", "tukui", "curse", "url", "folders", "forever", "notice"]


def main():
	src, commit = sys.argv[1], sys.argv[2]
	if not re.fullmatch(r"[0-9a-f]{40}", commit):
		sys.exit("give the full 40-character AddonForge commit")
	with open(src, encoding="utf-8") as f:
		upstream = json.load(f)
	if upstream.get("flavor") != "forever":
		sys.exit("not the Forever catalog")
	addons = []
	for a in upstream["addons"]:
		if a["id"] in DROP:
			continue
		if not (a.get("github") or a.get("wowi") or a.get("tukui") or a.get("curse") or a.get("url")):
			continue
		e = {k: a[k] for k in KEEP if a.get(k) not in (None, "", [])}
		if "forever" in a:
			e["forever"] = a["forever"]
		e["id"] = ID_MAP.get(a["id"], a["id"])
		if a["id"] in DESC:
			e["desc"] = DESC[a["id"]]
		if a["id"] in NOTICE:
			e["notice"] = NOTICE[a["id"]]
		if a["id"] in URL:
			e["url"] = URL[a["id"]]
			e.pop("forever", None)
		for k, v in e.items():
			if isinstance(v, str) and re.search(r"(?i)wago|addonforge|pocket forge", v):
				sys.exit("entry %s still names another app in %s: %s" % (a["id"], k, v))
		addons.append(e)
	data = {"source": "https://github.com/Topher121/AddonForge/blob/%s/catalog/forever.json" % commit, "updated": upstream.get("updated", ""), "addons": addons}
	text = json.dumps(data, ensure_ascii=False, indent="\t", sort_keys=False)
	out = (
		"// The addon catalog: where each addon's author publishes it. Generated by tools/build_catalog.py from the\n"
		"// AddonForge catalog (MIT License, Copyright (c) 2026 Pocket Forge Studios; see NOTICE). Do not edit by hand.\n"
		"namespace EldoUI.Updater.Core\n{\n\tstatic class CatalogData\n\t{\n"
		"\t\tpublic const string Commit = \"%s\";\n"
		"\t\tpublic const string Json = @\"%s\";\n\t}\n}\n" % (commit, text.replace('"', '""'))
	)
	with open("src/Core/CatalogData.cs", "w", encoding="utf-8", newline="\n") as f:
		f.write(out)
	print("%d addons written" % len(addons))


if __name__ == "__main__":
	main()
